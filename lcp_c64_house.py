def _get_bezel_overlay() -> Image.Image:
    global _BEZEL_OVERLAY_240
    if _BEZEL_OVERLAY_240 is not None:
        return _BEZEL_OVERLAY_240
    ov = Image.new("RGBA", (BASE_W, BASE_H), (0, 0, 0, 0))
    px = ov.load()
    r_in2 = R_WORLD * R_WORLD
    r_mid2 = (R_WORLD + 2) * (R_WORLD + 2)
    r_out2 = R_RING_O * R_RING_O
    for y in range(BASE_H):
        dy = y - CY
        for x in range(BASE_W):
            dx = x - CX
            d2 = dx * dx + dy * dy
            if d2 > r_out2:
                px[x, y] = C_BLK + (255,)
            elif d2 > r_mid2:
                px[x, y] = C_BLU + (255,)
            elif d2 >= r_in2:
                px[x, y] = C_LBL + (255,)
    _BEZEL_OVERLAY_240 = ov
    return ov


def _draw_diagonal_staircase(
    d: ImageDraw.ImageDraw,
    x0: int,
    y0: int,
    x1: int,
    y1: int,
    n_steps: int = 10,
) -> None:
    # Draw diagonal dark stringer beam
    d.line([(x0 - 2, y0), (x1 - 2, y1)], fill=C_BRN, width=3)
    d.line([(x0 + 3, y0), (x1 + 3, y1)], fill=C_BRN, width=2)
    for i in range(n_steps + 1):
        t = i / float(n_steps)
        sx = int(round(x0 + (x1 - x0) * t))
        sy = int(round(y0 + (y1 - y0) * t))
        d.rectangle([sx - 4, sy - 1, sx + 4, sy], fill=C_ORG)
        d.line([(sx - 4, sy - 1), (sx + 4, sy - 1)], fill=C_YEL if i % 2 == 0 else C_ORG)
    # Handrail + balusters
    d.line([(x0, y0 - 11), (x1, y1 - 11)], fill=C_BRN, width=1)
    for i in (0, 3, 6, 10):
        t = i / float(n_steps)
        bx = int(round(x0 + (x1 - x0) * t))
        by = int(round(y0 + (y1 - y0) * t))
        d.line([(bx, by - 11), (bx, by - 1)], fill=C_BRN)


