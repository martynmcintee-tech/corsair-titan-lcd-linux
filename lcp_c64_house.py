def _draw_c64_plaque(
    d: ImageDraw.ImageDraw,
    x0: int,
    y0: int,
    x1: int,
    y1: int,
    bg: tuple[int, int, int] = C_BLU,
    border: tuple[int, int, int] = C_LBL,
) -> None:
    # Classic beveled C64 status plaque with crisp 1px outer black & inner light-blue frame
    poly = [
        (x0 + 2, y0),
        (x1 - 2, y0),
        (x1, y0 + 2),
        (x1, y1 - 2),
        (x1 - 2, y1),
        (x0 + 2, y1),
        (x0, y1 - 2),
        (x0, y0 + 2),
    ]
    d.polygon(poly, fill=bg, outline=C_BLK)
    inner = [
        (x0 + 2, y0 + 1),
        (x1 - 2, y0 + 1),
        (x1 - 1, y0 + 2),
        (x1 - 1, y1 - 2),
        (x1 - 2, y1 - 1),
        (x0 + 2, y1 - 1),
        (x0 + 1, y1 - 2),
        (x0 + 1, y0 + 2),
    ]
    d.polygon(inner, outline=border)


def _temp_color(temp_c: int) -> tuple[int, int, int]:
    if temp_c >= 80:
        return C_FLS
    if temp_c >= 65:
        return C_YEL
    return C_LGN


