_GLYPH_CACHE: dict[tuple[str, tuple[int, int, int]], Image.Image] = {}


def _get_glyph(ch: str, color: tuple[int, int, int]) -> Image.Image:
    key = (ch, color)
    cached = _GLYPH_CACHE.get(key)
    if cached is not None:
        return cached
    rows = _FONT_5X7_RAW.get(ch) or _FONT_5X7_RAW["?"]
    im = Image.new("RGBA", (5, 7), (0, 0, 0, 0))
    px = im.load()
    rgba = color + (255,)
    for ry, row in enumerate(rows):
        for rx, c in enumerate(row):
            if c == "#":
                px[rx, ry] = rgba
    _GLYPH_CACHE[key] = im
    return im


def draw_pixel_text(
    canvas: Image.Image,
    x: int,
    y: int,
    text: str,
    color: tuple[int, int, int] = C_WHT,
    shadow: tuple[int, int, int] | None = None,
    center_x: bool = False,
) -> None:
    s = text.upper()
    if not s:
        return
    total_w = len(s) * 6 - 1
    cur_x = (x - total_w // 2) if center_x else x
    for ch in s:
        if ch != " ":
            if shadow is not None:
                sg = _get_glyph(ch, shadow)
                canvas.paste(sg, (cur_x + 1, y + 1), sg)
            g = _get_glyph(ch, color)
            canvas.paste(g, (cur_x, y), g)
        cur_x += 6


# ===========================================================================
# 3. Hex-Grid Sprite Compiler (Pure 16-Color VIC-II RGBA Sprites)
# ===========================================================================
def compile_sprite(
    rows: tuple[str, ...] | list[str],
    swap: dict[str, str] | None = None,
    flip_x: bool = False,
) -> Image.Image:
    h = len(rows)
    w = len(rows[0]) if h else 0
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            mapped = swap.get(ch, ch) if swap else ch
            rgb = PAL[int(mapped, 16)]
            tx = (w - 1 - x) if flip_x else x
            px[tx, y] = rgb + (255,)
    return im


